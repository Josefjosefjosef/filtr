export function safeImporterFailure(code) {
  const c = TMC_IMPORTER_ERROR[code] || TMC_IMPORTER_ERROR.TMC_INTERNAL_SAFE_FAILURE;
  return Object.freeze({
    ok: false,
    rejectCode: c,
    importerStatus: c,
    message: c,
  });
}
