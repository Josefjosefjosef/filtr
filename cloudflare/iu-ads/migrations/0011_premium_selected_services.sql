PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS premium_selected_categories (
  category_slug TEXT PRIMARY KEY,
  premium_capacity INTEGER NOT NULL DEFAULT 2 CHECK (premium_capacity IN (2, 4)),
  p2_first_published_at TEXT,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS premium_selected_placements (
  placement_id TEXT PRIMARY KEY,
  category_slug TEXT NOT NULL,
  position INTEGER NOT NULL CHECK (position BETWEEN 1 AND 4),
  current_price_cents INTEGER NOT NULL,
  currency TEXT NOT NULL DEFAULT 'CZK',
  active_campaign_id TEXT,
  updated_at TEXT NOT NULL,
  FOREIGN KEY (category_slug) REFERENCES premium_selected_categories(category_slug)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_premium_selected_placements_cat_pos
  ON premium_selected_placements(category_slug, position);

CREATE TABLE IF NOT EXISTS premium_order_price_snapshots (
  order_id TEXT PRIMARY KEY,
  placement_id TEXT NOT NULL,
  catalog_price_cents INTEGER NOT NULL,
  agreed_price_cents INTEGER NOT NULL,
  currency TEXT NOT NULL,
  duration_months INTEGER NOT NULL,
  ordered_at TEXT NOT NULL,
  FOREIGN KEY (order_id) REFERENCES orders(order_id)
);

